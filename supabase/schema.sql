-- ---------------------------------------------------------------------
-- 1. Профили пользователей и роли
-- ---------------------------------------------------------------------
-- Роль хранится в отдельной таблице, а не в user_metadata:
-- metadata пользователь может изменить сам, а эту колонку — нет.
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null default '' check (char_length(name) <= 80),
  role text not null default 'user' check (role in ('user', 'admin')),
  created_at timestamptz not null default now()
);

-- Проверка «текущий пользователь — администратор».
-- security definer: функция читает profiles в обход RLS, иначе политики зациклились бы.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles where id = auth.uid() and role = 'admin'
  );
$$;

-- При регистрации автоматически создаётся профиль с ролью 'user'.
-- Роль из данных регистрации НЕ берётся — стать админом через форму невозможно.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, name)
  values (
    new.id,
    left(coalesce(
      nullif(new.raw_user_meta_data ->> 'name', ''),
      nullif(new.raw_user_meta_data ->> 'full_name', ''),
      split_part(coalesce(new.email, ''), '@', 1)
    ), 80)
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Профили для пользователей, зарегистрированных до запуска скрипта.
insert into public.profiles (id, name)
select id, left(coalesce(nullif(raw_user_meta_data ->> 'name', ''), split_part(coalesce(email, ''), '@', 1)), 80)
from auth.users
on conflict (id) do nothing;

