create table if not exists public.cottages (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null check (char_length(btrim(name)) between 1 and 60),
  tier text not null default 'premium' check (tier in ('premium', 'atmosphere', 'natural')),
  tagline jsonb not null default '{}'::jsonb,      -- {"ru": "...", "en": "...", "kg": "..."}
  description jsonb not null default '{}'::jsonb,  -- {"ru": "...", "en": "...", "kg": "..."}
  amenities text[] not null default '{}',
  images text[] not null default '{}',
  price_weekday integer not null check (price_weekday between 0 and 10000000),
  price_weekend integer not null check (price_weekend between 0 and 10000000),
  capacity integer not null default 3 check (capacity between 1 and 20),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists cottages_updated_at on public.cottages;
create trigger cottages_updated_at
  before update on public.cottages
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------
-- 3. Отзывы
-- ---------------------------------------------------------------------
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 2 and 60),
  text text not null check (char_length(btrim(text)) between 10 and 1000),
  rating smallint not null check (rating between 1 and 5),
  cottage_id bigint references public.cottages (id) on delete set null,
  translations jsonb,  -- переводы исходных отзывов: {"en": {"name": "...", "text": "..."}, ...}
  approved boolean not null default false,  -- публикуется только после модерации
  user_id uuid default auth.uid() references auth.users (id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists reviews_approved_idx on public.reviews (approved, created_at desc);
create index if not exists reviews_cottage_idx on public.reviews (cottage_id);
-- Защита от повторной отправки одного и того же отзыва.
create unique index if not exists reviews_no_duplicates on public.reviews (lower(btrim(name)), md5(btrim(text)));

