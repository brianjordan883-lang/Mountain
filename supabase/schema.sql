-- profiles: свой профиль или любой — для админа; менять можно только своё имя.
drop policy if exists "profiles: read own or admin" on public.profiles;
create policy "profiles: read own or admin" on public.profiles
  for select to authenticated
  using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles: update own" on public.profiles;
create policy "profiles: update own" on public.profiles
  for update to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

-- cottages, site_settings, faqs: читают все, изменяет только админ.
drop policy if exists "cottages: public read" on public.cottages;
create policy "cottages: public read" on public.cottages for select to anon, authenticated using (true);
drop policy if exists "cottages: admin insert" on public.cottages;
create policy "cottages: admin insert" on public.cottages for insert to authenticated with check (public.is_admin());
drop policy if exists "cottages: admin update" on public.cottages;
create policy "cottages: admin update" on public.cottages for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "cottages: admin delete" on public.cottages;
create policy "cottages: admin delete" on public.cottages for delete to authenticated using (public.is_admin());

drop policy if exists "settings: public read" on public.site_settings;
create policy "settings: public read" on public.site_settings for select to anon, authenticated using (true);
drop policy if exists "settings: admin insert" on public.site_settings;
create policy "settings: admin insert" on public.site_settings for insert to authenticated with check (public.is_admin());
drop policy if exists "settings: admin update" on public.site_settings;
create policy "settings: admin update" on public.site_settings for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "settings: admin delete" on public.site_settings;
create policy "settings: admin delete" on public.site_settings for delete to authenticated using (public.is_admin());

drop policy if exists "faqs: public read" on public.faqs;
create policy "faqs: public read" on public.faqs for select to anon, authenticated using (true);
