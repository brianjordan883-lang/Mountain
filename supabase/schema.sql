-- ---------------------------------------------------------------------
-- 5. Бронирования
-- ---------------------------------------------------------------------
create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  cottage_id bigint references public.cottages (id) on delete set null,
  user_id uuid default auth.uid() references auth.users (id) on delete set null,
  guest_name text not null check (char_length(btrim(guest_name)) between 2 and 80),
  email text not null check (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
  phone text not null default '' check (char_length(phone) <= 30),
  check_in date not null,
  check_out date not null,
  guests smallint not null check (guests between 1 and 20),
  notes text not null default '' check (char_length(notes) <= 1000),
  total integer not null default 0 check (total >= 0),
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'paid', 'cancelled')),
  created_at timestamptz not null default now(),
  check (check_out > check_in),
  -- База сама не даст создать две активные брони одного домика на пересекающиеся даты.
  constraint bookings_no_overlap exclude using gist (
    cottage_id with =,
    daterange(check_in, check_out) with &&
  ) where (status <> 'cancelled')
);

create index if not exists bookings_user_idx on public.bookings (user_id);

-- Стоимость считает база, а не браузер: клиент не может подменить сумму.
create or replace function public.bookings_set_total()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  c public.cottages%rowtype;
  extra integer;
  nights integer;
begin
  select * into c from public.cottages where id = new.cottage_id;
  if not found then
    raise exception 'cottage_not_found' using errcode = '23503';
  end if;
  if new.guests > c.capacity then
    raise exception 'too_many_guests' using errcode = '23514';
  end if;

  select coalesce((value ->> 'extraGuest')::integer, 0) into extra
  from public.site_settings where key = 'stay';

  nights := new.check_out - new.check_in;
  -- Ночи с пятницы и субботы считаются по цене выходного дня.
  select coalesce(sum(case when extract(dow from d) in (5, 6) then c.price_weekend else c.price_weekday end), 0)
  into new.total
  from generate_series(new.check_in, new.check_out - 1, interval '1 day') as d;

  if new.guests > 2 then
    new.total := new.total + coalesce(extra, 0) * nights;
  end if;
  return new;
end;
$$;

drop trigger if exists bookings_total on public.bookings;
create trigger bookings_total
  before insert on public.bookings
  for each row execute function public.bookings_set_total();

-- Занятые даты домика (без имён и контактов гостей) — для проверки при бронировании.
create or replace function public.get_busy_ranges(p_cottage_id bigint)
returns table (check_in date, check_out date)
language sql
stable
security definer
set search_path = public
as $$
  select b.check_in, b.check_out
  from public.bookings b
  where b.cottage_id = p_cottage_id
    and b.status <> 'cancelled'
    and b.check_out >= current_date
  order by b.check_in;
$$;

-- ---------------------------------------------------------------------
-- 6. Права доступа (GRANT) — какие колонки вообще можно трогать
-- ---------------------------------------------------------------------
-- Пользователь может записать только «свои» поля. Например, при отправке отзыва
-- нельзя передать approved = true или чужой user_id: этих колонок нет в GRANT.
revoke all on public.profiles, public.cottages, public.reviews, public.site_settings, public.faqs, public.bookings
  from anon, authenticated;

grant select on public.cottages, public.reviews, public.site_settings, public.faqs to anon, authenticated;
grant select on public.profiles, public.bookings to authenticated;

grant update (name) on public.profiles to authenticated;

grant insert, update, delete on public.cottages, public.site_settings, public.faqs to authenticated;

grant insert (name, text, rating, cottage_id) on public.reviews to anon, authenticated;
grant update (approved, name, text, rating, cottage_id, translations) on public.reviews to authenticated;
grant delete on public.reviews to authenticated;

grant insert (cottage_id, guest_name, email, phone, check_in, check_out, guests, notes) on public.bookings to anon, authenticated;
grant update (status) on public.bookings to authenticated;
grant delete on public.bookings to authenticated;

revoke execute on function public.handle_new_user() from public, anon, authenticated;
revoke execute on function public.bookings_set_total() from public, anon, authenticated;
grant execute on function public.is_admin() to anon, authenticated;
grant execute on function public.get_busy_ranges(bigint) to anon, authenticated;

