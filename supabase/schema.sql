create policy "faqs: admin insert" on public.faqs for insert to authenticated with check (public.is_admin());
drop policy if exists "faqs: admin update" on public.faqs;
create policy "faqs: admin update" on public.faqs for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "faqs: admin delete" on public.faqs;
create policy "faqs: admin delete" on public.faqs for delete to authenticated using (public.is_admin());

-- reviews: публично видны только одобренные; админ видит все.
drop policy if exists "reviews: read approved or admin" on public.reviews;
create policy "reviews: read approved or admin" on public.reviews
  for select to anon, authenticated
  using (approved or public.is_admin());

-- Любой посетитель может отправить отзыв, но только неодобренный и только от своего имени.
drop policy if exists "reviews: anyone can submit" on public.reviews;
create policy "reviews: anyone can submit" on public.reviews
  for insert to anon, authenticated
  with check (approved = false and (user_id is null or user_id = auth.uid()));

drop policy if exists "reviews: admin update" on public.reviews;
create policy "reviews: admin update" on public.reviews for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "reviews: admin delete" on public.reviews;
create policy "reviews: admin delete" on public.reviews for delete to authenticated using (public.is_admin());

-- bookings: создать может любой (только «ожидает», только на будущие даты);
-- видит свои брони пользователь, все — админ.
drop policy if exists "bookings: anyone can create" on public.bookings;
create policy "bookings: anyone can create" on public.bookings
  for insert to anon, authenticated
  with check (
    status = 'pending'
    and cottage_id is not null
    and check_in >= current_date
    and (user_id is null or user_id = auth.uid())
  );

drop policy if exists "bookings: read own or admin" on public.bookings;
create policy "bookings: read own or admin" on public.bookings
  for select to authenticated
  using (user_id = auth.uid() or public.is_admin());

drop policy if exists "bookings: admin update" on public.bookings;
create policy "bookings: admin update" on public.bookings for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- Пользователь может только отменить свою неподтверждённую бронь.
drop policy if exists "bookings: cancel own pending" on public.bookings;
create policy "bookings: cancel own pending" on public.bookings
  for update to authenticated
  using (user_id = auth.uid() and status = 'pending')
  with check (user_id = auth.uid() and status = 'cancelled');

drop policy if exists "bookings: admin delete" on public.bookings;
create policy "bookings: admin delete" on public.bookings for delete to authenticated using (public.is_admin());

